CREATE TABLE monitoring_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    street VARCHAR(160) NOT NULL,
    neighborhood VARCHAR(100) NOT NULL,
    city VARCHAR(80) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_monitoring_point_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_monitoring_point_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE flood_occurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitoring_point_id BIGINT NOT NULL,
    description VARCHAR(500) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    source VARCHAR(25) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_occurrence_monitoring_point FOREIGN KEY (monitoring_point_id)
        REFERENCES monitoring_points (id),
    CONSTRAINT ck_occurrence_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_occurrence_status CHECK (status IN ('REPORTED', 'CONFIRMED', 'IN_PROGRESS', 'RESOLVED')),
    CONSTRAINT ck_occurrence_source CHECK (source IN ('CITIZEN_REPORT', 'FIELD_AGENT', 'SENSOR', 'PUBLIC_DATA', 'DEMONSTRATION'))
);

CREATE INDEX idx_monitoring_points_neighborhood ON monitoring_points (neighborhood);
CREATE INDEX idx_flood_occurrences_status ON flood_occurrences (status);
CREATE INDEX idx_flood_occurrences_occurred_at ON flood_occurrences (occurred_at);
CREATE INDEX idx_flood_occurrences_monitoring_point ON flood_occurrences (monitoring_point_id);
